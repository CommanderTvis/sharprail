using System.Collections.Generic;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace SharpRail.Plugins.Isolation.Generator;

/// <summary>
/// The proxies and dispatchers. Runner direction: a proxy per root context and per interface a <c>LocalInRunner</c>
/// member hands out, an interface for the members the runner implements by hand, and the invoker of lent callbacks.
/// Trusted direction: the dispatcher that replays a call onto the real context, with callback proxies that call back.
/// </summary>
internal sealed partial class Emitter
{
    private const string Iso = "global::SharpRail.Plugins.Isolation.";

    private static readonly SymbolDisplayFormat Format = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private string Members => "global::" + space + "." + Short + "Members";

    public IEnumerable<(string Hint, string Source)> Runner()
    {
        var local = table.Members.Where(member => member.Role == MemberRole.Root && !member.Pending && member.Crossing == "LocalInRunner" && Accessed(member) is null).ToList();
        yield return (Short + "Local.g.cs", LocalInterface(local));
        yield return ("Isolated" + Short + ".g.cs", Proxy(table.Root, $"Isolated{Short}", null));
        foreach (var (handle, _) in table.Handles)
            yield return ("Isolated" + Trim(handle) + ".g.cs", Proxy(handle, "Isolated" + Trim(handle), handle));
        yield return (Short + "Callbacks.g.cs", Invoker());
    }

    public IEnumerable<(string Hint, string Source)> Trusted()
    {
        yield return (Short + "Dispatcher.g.cs", Dispatcher());
    }

    private static string Trim(INamedTypeSymbol type) => type.TypeKind == TypeKind.Interface && type.Name.StartsWith("I") ? type.Name.Substring(1) : type.Name;

    private static string Type(ITypeSymbol type) => type.ToDisplayString(Format);

    private static string Id(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private static string Camel(string name) => char.ToLowerInvariant(name[0]) + name.Substring(1);

    private static bool IsToken(ITypeSymbol type) => ModelBuilder.Is(type, "System.Threading.CancellationToken");

    private static bool IsSplit(ITypeSymbol type) =>
        type is INamedTypeSymbol record && ModelBuilder.IsApi(record) && record.TypeKind == TypeKind.Class && ModelBuilder.HasCallbacks(record);

    private static StringBuilder Header(string space)
    {
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("#nullable enable");
        text.AppendLine("#pragma warning disable CS1998, CS9113");
        text.AppendLine($"namespace {space};");
        text.AppendLine();
        return text;
    }

    private Member? Find(ISymbol symbol) => table.Members.FirstOrDefault(member => SymbolEqualityComparer.Default.Equals(member.Symbol, symbol));

    private Member? FindCallback(Member parent, IParameterSymbol parameter) =>
        table.Members.FirstOrDefault(member => member.Role == MemberRole.CallbackParameter && member.Parent == parent && member.Symbol.Name == parameter.Name);

    /// <summary>The interface a <c>LocalInRunner</c> member hands out as a generated proxy, if it does.</summary>
    private INamedTypeSymbol? Accessed(Member member) => table.Handles.FirstOrDefault(entry => entry.Accessor == member).Interface;

    private string LocalInterface(List<Member> local)
    {
        var text = Header(space);
        text.AppendLine($"/// <summary>The members of <c>{table.Root.Name}</c> the runner implements itself (<c>LocalInRunner</c>).</summary>");
        text.AppendLine($"internal interface I{Short}Local");
        text.AppendLine("{");
        foreach (var member in local)
        {
            if (member.Symbol is IPropertySymbol property)
                text.AppendLine($"    {Type(property.Type)} {Id(property.Name)} {{ get; }}");
            else if (member.Symbol is IMethodSymbol method)
                text.AppendLine($"    {Type(method.ReturnType)} {Id(method.Name)}{TypeParameters(method)}({Parameters(method, defaults: true)}){Constraints(method)};");
        }
        text.AppendLine("}");
        return text.ToString();
    }

    private static string TypeParameters(IMethodSymbol method) =>
        method.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", method.TypeParameters.Select(parameter => parameter.Name)) + ">";

    private static string Parameters(IMethodSymbol method, bool defaults) => string.Join(", ", method.Parameters.Select(parameter =>
    {
        var text = $"{Type(parameter.Type)} {Id(parameter.Name)}";
        if (defaults && parameter.HasExplicitDefaultValue)
            text += " = " + (parameter.ExplicitDefaultValue is null ? "default" : SymbolDisplay.FormatPrimitive(parameter.ExplicitDefaultValue, quoteStrings: true, useHexadecimalNumbers: false));
        return text;
    }));

    private static string Constraints(IMethodSymbol method)
    {
        var text = new StringBuilder();
        foreach (var parameter in method.TypeParameters)
        {
            var parts = new List<string>();
            if (parameter.HasReferenceTypeConstraint) parts.Add(parameter.ReferenceTypeConstraintNullableAnnotation == NullableAnnotation.Annotated ? "class?" : "class");
            if (parameter.HasValueTypeConstraint) parts.Add("struct");
            if (parameter.HasNotNullConstraint) parts.Add("notnull");
            parts.AddRange(parameter.ConstraintTypes.Select(Type));
            if (parameter.HasConstructorConstraint) parts.Add("new()");
            if (parts.Count > 0) text.Append($" where {parameter.Name} : {string.Join(", ", parts)}");
        }
        return text.ToString();
    }

    private static string Arguments(IMethodSymbol method) => string.Join(", ", method.Parameters.Select(parameter => Id(parameter.Name)));

    /// <summary>
    /// A proxy implementing <paramref name="type"/> explicitly, every member included, so no default interface member
    /// answers for it (SRI005). A handle interface's proxy carries the accessor's arguments as <c>via</c>.
    /// </summary>
    private string Proxy(INamedTypeSymbol type, string name, INamedTypeSymbol? handle)
    {
        var text = Header(space);
        var iface = Type(type);
        var parameters = handle is null
            ? $"{Iso}IIsolatedRuntime runtime, long target, I{Short}Local local"
            : $"{Iso}IIsolatedRuntime runtime, long target, string via";
        text.AppendLine($"/// <summary>What an isolated plugin holds as <c>{type.Name}</c>: calls cross the plugin channel; pending members throw.</summary>");
        text.AppendLine($"internal sealed class {name}({parameters}) : {iface}");
        text.AppendLine("{");
        var implemented = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        foreach (var symbol in ModelBuilder.Surface(type))
        {
            implemented.Add(symbol);
            var member = Find(symbol);
            if (symbol is IPropertySymbol property)
            {
                text.AppendLine($"    {Type(property.Type)} {iface}.{Id(property.Name)}");
                text.AppendLine("    {");
                text.AppendLine("        get");
                text.AppendLine("        {");
                Body(text, member, symbol, property.Type, [], "            ");
                text.AppendLine("        }");
                text.AppendLine("    }");
            }
            else if (symbol is IMethodSymbol method)
            {
                var async = member is { Pending: false, Crossing: null } && ModelBuilder.IsTask(method.ReturnType);
                text.AppendLine($"    {(async ? "async " : "")}{Type(method.ReturnType)} {iface}.{Id(method.Name)}{TypeParameters(method)}({Parameters(method, defaults: false)})");
                text.AppendLine("    {");
                Body(text, member, symbol, method.ReturnType, method.Parameters, "        ");
                text.AppendLine("    }");
            }
        }
        text.AppendLine("}");
        foreach (var symbol in type.GetMembers().Where(symbol => symbol is IMethodSymbol { IsAbstract: false, IsStatic: false, MethodKind: MethodKind.Ordinary } or IPropertySymbol { IsAbstract: false, IsStatic: false }))
        {
            if (implemented.Contains(symbol)) continue;
            Diagnostics.Add(Diagnostic.Create(Rules.DefaultMember, Location.None,
                $"The generated {name} does not implement the default {symbol.ToDisplayString()}; the generator must emit every member"));
        }
        return text.ToString();
    }

    private void Body(StringBuilder text, Member? member, ISymbol symbol, ITypeSymbol returnType, IEnumerable<IParameterSymbol> parameters, string indent)
    {
        if (member is null || member.Pending)
        {
            text.AppendLine($"{indent}throw {Iso}IsolationPending.Member(\"{symbol.ContainingType.Name}.{symbol.Name}\");");
            return;
        }
        var list = parameters.ToList();
        if (member.Crossing == "LocalInRunner")
        {
            if (Accessed(member) is { } handle)
            {
                Payload(text, member, list, indent);
                text.AppendLine($"{indent}return new Isolated{Trim(handle)}(runtime, target, payload.Finish());");
            }
            else if (symbol is IMethodSymbol method)
                text.AppendLine($"{indent}{(returnType.SpecialType == SpecialType.System_Void ? "" : "return ")}local.{Id(method.Name)}{TypeParameters(method)}({Arguments(method)});");
            else text.AppendLine($"{indent}return local.{Id(symbol.Name)};");
            return;
        }
        Payload(text, member, list, indent);
        if (member.Crossing == "Mirrored")
        {
            text.AppendLine($"{indent}return runtime.ReadMirror<{Type(returnType)}>({Members}.{member.Name}, target, payload.Finish());");
            return;
        }
        if (ModelBuilder.IsTask(returnType))
        {
            var token = list.FirstOrDefault(parameter => IsToken(parameter.Type))?.Name;
            var call = $"await runtime.CallAsync({Members}.{member.Name}, target, payload.Finish(), {(token is null ? "default" : Id(token))})";
            text.AppendLine(ModelBuilder.IsResultless(returnType)
                ? $"{indent}{call};"
                : $"{indent}return {Iso}IsoPayload.Read<{Type(ModelBuilder.Unwrap(returnType))}>({call});");
            return;
        }
        text.AppendLine($"{indent}runtime.OneWay({Members}.{member.Name}, target, payload.Finish());");
    }

    /// <summary>Writes the arguments: by value, lent callbacks as handles, and records split into data and handles.</summary>
    private void Payload(StringBuilder text, Member member, List<IParameterSymbol> parameters, string indent)
    {
        text.AppendLine($"{indent}var payload = new {Iso}IsoPayload();");
        if (member.Role == MemberRole.Handle) text.AppendLine($"{indent}payload.Raw(via);");
        foreach (var parameter in parameters)
        {
            var name = Id(parameter.Name);
            if (IsToken(parameter.Type)) continue;
            if (parameter.Type.TypeKind == TypeKind.Delegate)
            {
                text.AppendLine($"{indent}payload.Handle({Lend(name, parameter.Type)});");
                continue;
            }
            if (IsSplit(parameter.Type))
            {
                var record = (INamedTypeSymbol)parameter.Type;
                var properties = ModelBuilder.Surface(record).OfType<IPropertySymbol>().ToList();
                foreach (var property in properties.Where(property => property.Type.TypeKind == TypeKind.Delegate && Find(property) is { Pending: true }))
                    text.AppendLine($"{indent}if ({name}.{Id(property.Name)} is not null) throw {Iso}IsolationPending.Member(\"{record.Name}.{property.Name}\");");
                text.AppendLine($"{indent}payload.Object();");
                foreach (var property in properties)
                {
                    if (property.Type.TypeKind != TypeKind.Delegate)
                        text.AppendLine($"{indent}payload.Name(\"{Camel(property.Name)}\").Value<{Type(property.Type)}>({name}.{Id(property.Name)});");
                    else if (Find(property) is not { Pending: true })
                        text.AppendLine($"{indent}payload.Name(\"{Camel(property.Name)}\").Handle({Lend($"{name}.{Id(property.Name)}", property.Type)});");
                }
                text.AppendLine($"{indent}payload.End();");
                continue;
            }
            text.AppendLine($"{indent}payload.Value<{Type(parameter.Type)}>({name});");
        }
    }

    private static string Lend(string expression, ITypeSymbol type) =>
        type.NullableAnnotation == NullableAnnotation.Annotated ? $"{expression} is null ? null : runtime.Lend({expression})" : $"runtime.Lend({expression})";

    /// <summary>The runner's invoker: runs a lent callback the trusted side calls, by its member id.</summary>
    private string Invoker()
    {
        var text = Header(space);
        var callbacks = table.Members.Where(member => member.IsCallback && !member.Pending).ToList();
        const string Signature = "global::System.Func<object, string> surface, global::System.Threading.CancellationToken cancellationToken";
        text.AppendLine($"/// <summary>Runs the callbacks an isolated plugin lent through <c>{table.Root.Name}</c>; a factory's control goes to <c>surface</c>, which answers its surface.</summary>");
        text.AppendLine($"internal static class {Short}Callbacks");
        text.AppendLine("{");
        text.AppendLine($"    public static global::System.Threading.Tasks.ValueTask<string> InvokeAsync(int member, object target, string payload, {Signature}) => member switch");
        text.AppendLine("    {");
        foreach (var member in callbacks)
            text.AppendLine($"        {Members}.{member.Name} => {member.Name}(({Type(member.Delegate!)})target, {Iso}IsoArgs.Parse(payload), surface, cancellationToken),");
        text.AppendLine($"        _ => throw new {Iso}IsoCallException({Iso}IsoError.Unknown, \"Not a callback of {table.Root.Name}.\"),");
        text.AppendLine("    };");
        foreach (var member in callbacks)
        {
            var invoke = member.Delegate!.DelegateInvokeMethod!;
            var (returnType, isAsync, isVoid) = ModelBuilder.Returns(invoke);
            text.AppendLine();
            text.AppendLine($"    private static {(isAsync ? "async " : "")}global::System.Threading.Tasks.ValueTask<string> {member.Name}({Type(member.Delegate!)} callback, {Iso}IsoArgs args, {Signature})");
            text.AppendLine("    {");
            var arguments = new List<string>();
            var index = 0;
            foreach (var parameter in invoke.Parameters)
            {
                if (IsToken(parameter.Type))
                {
                    arguments.Add("cancellationToken");
                    continue;
                }
                text.AppendLine($"        var p{index} = args.Value<{Type(parameter.Type)}>({index});");
                arguments.Add("p" + index++);
            }
            var target = member.Delegate!.NullableAnnotation == NullableAnnotation.Annotated ? "callback!" : "callback";
            var call = $"{target}({string.Join(", ", arguments)})";
            if (ModelBuilder.IsControl(returnType)) text.AppendLine($"        return new(surface({call}));");
            else if (isVoid)
            {
                text.AppendLine($"        {call};");
                text.AppendLine("        return new(\"\");");
            }
            else if (isAsync && ModelBuilder.IsResultless(returnType))
            {
                text.AppendLine($"        await {call};");
                text.AppendLine("        return \"\";");
            }
            else if (isAsync) text.AppendLine($"        return {Iso}IsoPayload.Result<{Type(ModelBuilder.Unwrap(returnType))}>(await {call});");
            else text.AppendLine($"        return new({Iso}IsoPayload.Result<{Type(returnType)}>({call}));");
            text.AppendLine("    }");
        }
        text.AppendLine("}");
        return text.ToString();
    }

    /// <summary>The trusted side's dispatcher: replays a call from the plugin process onto the real context.</summary>
    private string Dispatcher()
    {
        var text = Header(space);
        var root = Type(table.Root);
        var dispatched = table.Members.Where(member => member.Role is MemberRole.Root or MemberRole.Handle && !member.Pending && member.Crossing is null).ToList();
        const string Signature = "global::System.Threading.CancellationToken cancellationToken";
        text.AppendLine($"/// <summary>Replays the calls and one-way messages an isolated plugin sends through <c>{table.Root.Name}</c> onto the real context.</summary>");
        text.AppendLine($"public static class {Short}Dispatcher");
        text.AppendLine("{");
        text.AppendLine($"    public static global::System.Threading.Tasks.ValueTask<string> DispatchAsync(int member, string payload, {root} target, {Iso}IIsolatedCallbacks callbacks, {Signature}) => member switch");
        text.AppendLine("    {");
        foreach (var member in dispatched)
            text.AppendLine($"        {Members}.{member.Name} => {member.Name}({Iso}IsoArgs.Parse(payload), target, callbacks, cancellationToken),");
        text.AppendLine($"        _ => throw new {Iso}IsoCallException({Iso}IsoError.Unknown, \"Not a member of {table.Root.Name} the isolated runtime implements.\"),");
        text.AppendLine("    };");
        foreach (var member in dispatched)
        {
            var method = (IMethodSymbol)member.Symbol;
            var (returnType, isAsync, isVoid) = ModelBuilder.Returns(method);
            text.AppendLine();
            text.AppendLine($"    private static {(isAsync ? "async " : "")}global::System.Threading.Tasks.ValueTask<string> {member.Name}({Iso}IsoArgs args, {root} target, {Iso}IIsolatedCallbacks callbacks, {Signature})");
            text.AppendLine("    {");
            var owner = "target";
            var position = 0;
            if (member.Role == MemberRole.Handle)
            {
                var accessor = member.Accessor!;
                text.AppendLine("        var via = args.Nested(0);");
                var viaArguments = accessor.Symbol is IMethodSymbol accessorMethod
                    ? "(" + string.Join(", ", accessorMethod.Parameters.Select((parameter, index) => $"via.Value<{Type(parameter.Type)}>({index})")) + ")"
                    : "";
                text.AppendLine($"        var owner = target.{Id(accessor.Symbol.Name)}{viaArguments};");
                owner = "owner";
                position = 1;
            }
            var substitutes = new Dictionary<ITypeSymbol, string>(SymbolEqualityComparer.Default);
            foreach (var parameter in method.TypeParameters)
                substitutes[parameter] = parameter.HasReferenceTypeConstraint ? "global::System.Text.Json.Nodes.JsonObject" : "global::System.Text.Json.JsonElement";
            string Closed(ITypeSymbol type) => substitutes.TryGetValue(type, out var closed) ? closed : Type(type);
            var arguments = new List<string>();
            foreach (var parameter in method.Parameters)
            {
                if (IsToken(parameter.Type))
                {
                    arguments.Add("cancellationToken");
                    continue;
                }
                var name = "a" + position;
                if (parameter.Type.TypeKind == TypeKind.Delegate)
                {
                    var proxy = CallbackProxy(FindCallback(member, parameter)!, (INamedTypeSymbol)parameter.Type, "h" + position);
                    text.AppendLine($"        var {name} = args.Handle({position}) is {{ }} h{position} ? {proxy} : null;");
                    if (parameter.Type.NullableAnnotation != NullableAnnotation.Annotated) name += " ?? throw new " + Iso + "IsoCallException(" + Iso + "IsoError.InvalidParams, \"" + parameter.Name + " is missing.\")";
                }
                else if (IsSplit(parameter.Type)) text.AppendLine($"        var {name} = {Construct((INamedTypeSymbol)parameter.Type, $"args.Object({position})")};");
                else text.AppendLine($"        var {name} = args.Value<{Closed(parameter.Type)}>({position});");
                arguments.Add(name);
                position++;
            }
            var typeArguments = method.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", method.TypeParameters.Select(parameter => substitutes[parameter])) + ">";
            var call = $"{owner}.{Id(method.Name)}{typeArguments}({string.Join(", ", arguments)})";
            if (isVoid)
            {
                text.AppendLine($"        {call};");
                text.AppendLine("        return new(\"\");");
            }
            else if (ModelBuilder.IsResultless(returnType))
            {
                text.AppendLine($"        await {call};");
                text.AppendLine("        return \"\";");
            }
            else text.AppendLine($"        return {Iso}IsoPayload.Result<{Closed(ModelBuilder.Unwrap(returnType))}>(await {call});");
            text.AppendLine("    }");
        }
        text.AppendLine("}");
        return text.ToString();
    }

    /// <summary>Rebuilds a record the plugin passed: data from JSON, callbacks as proxies over their handles.</summary>
    private string Construct(INamedTypeSymbol record, string source)
    {
        var properties = ModelBuilder.Surface(record).OfType<IPropertySymbol>().ToList();
        var constructor = record.InstanceConstructors
            .Where(candidate => candidate.DeclaredAccessibility == Accessibility.Public
                && !(candidate.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(candidate.Parameters[0].Type, record)))
            .OrderByDescending(candidate => candidate.Parameters.Length)
            .First();
        string Read(IPropertySymbol property)
        {
            var json = Camel(property.Name);
            if (property.Type.TypeKind != TypeKind.Delegate) return $"o.Value<{Type(property.Type)}>(\"{json}\")";
            var callback = Find(property);
            if (callback is null || callback.Pending) return "default!";
            var missing = property.Type.NullableAnnotation == NullableAnnotation.Annotated
                ? "null"
                : $"throw new {Iso}IsoCallException({Iso}IsoError.InvalidParams, \"{record.Name}.{property.Name} is missing.\")";
            return $"(o.Handle(\"{json}\") is {{ }} h{property.Name} ? {CallbackProxy(callback, (INamedTypeSymbol)property.Type, "h" + property.Name)} : {missing})";
        }
        var positional = constructor.Parameters
            .Select(parameter => properties.First(property => string.Equals(property.Name, parameter.Name, System.StringComparison.OrdinalIgnoreCase))).ToList();
        var initialized = properties.Where(property => !positional.Contains(property, SymbolEqualityComparer.Default) && property.SetMethod is not null
            && Find(property) is not { Pending: true }).ToList();
        var text = new StringBuilder($"((global::System.Func<{Iso}IsoObject, {Type(record)}>)(o => new {Type(record)}({string.Join(", ", positional.Select(Read))})");
        if (initialized.Count > 0) text.Append(" { " + string.Join(", ", initialized.Select(property => $"{Id(property.Name)} = {Read(property)}")) + " }");
        text.Append($"))({source})");
        return text.ToString();
    }

    /// <summary>A delegate that calls a lent callback back in the plugin process.</summary>
    private string CallbackProxy(Member callback, INamedTypeSymbol type, string handle)
    {
        var invoke = type.DelegateInvokeMethod!;
        var (returnType, isAsync, isVoid) = ModelBuilder.Returns(invoke);
        var names = invoke.Parameters.Select((_, index) => "p" + index).ToList();
        var token = invoke.Parameters.Select((parameter, index) => (parameter, index)).FirstOrDefault(entry => IsToken(entry.parameter.Type));
        var payload = new StringBuilder($"new {Iso}IsoPayload()");
        for (var index = 0; index < invoke.Parameters.Length; index++)
            if (!IsToken(invoke.Parameters[index].Type)) payload.Append($".Value<{Type(invoke.Parameters[index].Type)}>(p{index})");
        payload.Append(".Finish()");
        var id = $"{Members}.{callback.Name}";
        string body;
        if (ModelBuilder.IsControl(returnType)) body = $"({Type(returnType)})callbacks.Surface({id}, {handle}, {payload})";
        else if (isVoid) body = $"callbacks.OneWay({id}, {handle}, {payload})";
        else if (isAsync)
        {
            var call = $"await callbacks.CallAsync({id}, {handle}, {payload}, {(token.parameter is null ? "default" : "p" + token.index)})";
            body = ModelBuilder.IsResultless(returnType) ? $"{{ {call}; }}" : $"{Iso}IsoPayload.Read<{Type(ModelBuilder.Unwrap(returnType))}>({call})";
        }
        else body = $"callbacks.Sync<{Type(returnType)}>({id}, {handle}, {payload}, \"{callback.Crossing}\", static result => {Iso}IsoPayload.Read<{Type(returnType)}>(result))";
        return $"new {Type(type.WithNullableAnnotation(NullableAnnotation.NotAnnotated))}({(isAsync ? "async " : "")}({string.Join(", ", names)}) => {body})";
    }
