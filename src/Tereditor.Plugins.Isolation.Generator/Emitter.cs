using System.Collections.Generic;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;

namespace Tereditor.Plugins.Isolation.Generator;

/// <summary>Writes the generated sources for one member table.</summary>
internal sealed partial class Emitter
{
    private readonly Table table;
    private readonly string space;

    public Emitter(Table table, string space)
    {
        this.table = table;
        this.space = space;
    }

    public List<Diagnostic> Diagnostics { get; } = [];

    private string Short => IsolationGenerator.Short(table.Root);

    /// <summary>The member table: an id constant per member, every entry, and the hash both sides compare at the handshake.</summary>
    public static string Table(Table table, string space)
    {
        var name = IsolationGenerator.Short(table.Root) + "Members";
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("#nullable enable");
        text.AppendLine($"namespace {space};");
        text.AppendLine();
        text.AppendLine($"/// <summary>The isolation member table of <c>{table.Root.Name}</c>: what crosses, how, and under which permission.</summary>");
        text.AppendLine($"public static class {name}");
        text.AppendLine("{");
        text.AppendLine($"    /// <summary>The table's hash; the runner and the trusted side refuse each other when theirs differ.</summary>");
        text.AppendLine($"    public const string Hash = \"{table.Hash}\";");
        foreach (var member in table.Members)
            text.AppendLine($"    public const int {member.Name} = unchecked((int)0x{member.Id:x8});");
        text.AppendLine();
        text.AppendLine("    /// <summary>Every member, sorted by documentation-comment id.</summary>");
        text.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<global::Tereditor.Plugins.Isolation.IsolationMember> Table { get; } =");
        text.AppendLine("    [");
        foreach (var member in table.Members)
            text.AppendLine($"        new({member.Name}, {Literal(member.DocId)}, {Literal(member.Permission)}, {Literal(member.Condition)}, {(member.Ambient ? "true" : "false")}, {Literal(member.Crossing ?? "")}, {(member.Pending ? "true" : "false")}),");
        text.AppendLine("    ];");
        text.AppendLine("}");
        return text.ToString();
    }

    public static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}