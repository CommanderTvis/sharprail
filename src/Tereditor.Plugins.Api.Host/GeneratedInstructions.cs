using System.Text.RegularExpressions;

namespace SharpRail.Plugins.Api.Host;

/// <summary>
/// The instruction files SharpRail generates for agent sessions (<c>thinkrail-prompt-*.md</c> and Claude Code's
/// per-workspace <c>workspaces/*.md</c> under the state directory). They are never the user's to edit: they are rewritten
/// atomically from the sections on every write, left read-only on disk, and the host opens them read-only.
/// </summary>
public static partial class GeneratedInstructions
{
    /// <summary>The notice an editor shows over a generated instructions file.</summary>
    public const string Notice = "Generated by SharpRail. Turn sections off in Context › SharpRail's instructions.";

    /// <summary>The host state directory: <c>SHARPRAIL_STATE_DIR</c>, else <c>~/.sharprail</c>.</summary>
    public static string StateDirectory() =>
        Environment.GetEnvironmentVariable("SHARPRAIL_STATE_DIR") is { Length: > 0 } configured ? configured
            : Path.Combine(Environment.GetEnvironmentVariable("HOME") is { Length: > 0 } home ? home : Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".sharprail");

    [GeneratedRegex(@"^[^/]+/(thinkrail-prompt-[a-z]+\.md|workspaces/[0-9A-F]{16}\.md)$")]
    private static partial Regex GeneratedPath();

    /// <summary>Whether <paramref name="path"/> is a generated instructions file.</summary>
    public static bool Owns(string path)
    {
        if (!Path.IsPathFullyQualified(path)) return false;
        var relative = Path.GetRelativePath(Path.GetFullPath(StateDirectory()), Path.GetFullPath(path)).Replace('\\', '/');
        return GeneratedPath().IsMatch(relative);
    }

    /// <summary>
    /// Makes <paramref name="path"/> hold exactly <paramref name="text"/>. A file whose text differs (a hand edit included)
    /// is replaced by writing a temporary file and renaming it over the old one, so readers never see a partial file. On
    /// POSIX the file is left <c>0444</c>, so other editors warn; the rename needs only the directory to be writable. Windows
    /// keeps a normal file: its read-only attribute blocks replacing and recursively deleting the folder, which cleanup and
    /// tools rely on. Returns whether the file was rewritten.
    /// </summary>
    public static bool Write(string path, string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        if (File.Exists(path) && File.ReadAllText(path) == text) { MakeReadOnly(path); return false; }
        var temporary = path + "." + Environment.ProcessId + "." + Guid.NewGuid().ToString("N")[..8] + ".tmp";
        try
        {
            File.WriteAllText(temporary, text);
            MakeReadOnly(temporary);
            File.Move(temporary, path, overwrite: true);
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
        return true;
    }

    private const UnixFileMode ReadOnlyMode = UnixFileMode.UserRead | UnixFileMode.GroupRead | UnixFileMode.OtherRead;

    private static void MakeReadOnly(string path)
    {
        if (!OperatingSystem.IsWindows() && File.GetUnixFileMode(path) != ReadOnlyMode) File.SetUnixFileMode(path, ReadOnlyMode);
    }
}