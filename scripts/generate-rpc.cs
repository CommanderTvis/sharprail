// Generates typed WebSocket clients, direct dispatch and the protobuf payload codec from the host contracts.
// Run from the checkout root: dotnet run --file scripts/generate-rpc.cs
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

const string Header = "// Generated by scripts/generate-rpc.cs from the host contracts.\n";
var utf8 = new UTF8Encoding(false);
string Read(string path) => File.ReadAllText(path).Replace("\r\n", "\n");
string[] Sorted(string directory, string pattern) => Directory.GetFiles(directory, pattern).OrderBy(path => path, StringComparer.Ordinal).ToArray();
int Fail(string message) { Console.Error.WriteLine(message); Environment.Exit(1); return 1; }

var services = new OrderedDictionary<string, List<(string Kind, string Reply, string Method, string Request, string Arg)>>();
foreach (var path in Sorted("src/Tereditor.Host.Protocol", "*Contract.cs"))
{
    var source = Read(path);
    var match = Regex.Match(source, @"public (?:partial )?interface (I\w+Rpc)");
    if (!match.Success) continue;
    if (!services.TryGetValue(match.Groups[1].Value, out var list)) services[match.Groups[1].Value] = list = [];
    foreach (Match m in Regex.Matches(source, @"(ValueTask|IAsyncEnumerable)<(\w+)> (\w+)\((IAsyncEnumerable<\w+>|\w+) (\w+), CallContext context = default\);"))
        list.Add((m.Groups[1].Value, m.Groups[2].Value, m.Groups[3].Value, m.Groups[4].Value, m.Groups[5].Value));
}
var client = new StringBuilder(Header + "namespace Tereditor.Host.Protocol;\n\npublic static class RpcServices\n{\n    public static T Create<T>(IRpcClient client) => (T)(object)(typeof(T).Name switch\n    {\n");
foreach (var service in services.Keys)
    client.Append($"        nameof({service}) => new {service[1..]}Client(client),\n");
client.Append("        _ => throw new NotSupportedException(typeof(T).FullName)\n    });\n");
var server = new StringBuilder(Header + "using Tereditor.Host.Protocol;\n\nnamespace Tereditor.Host.Remote;\n\ninternal static class RpcDispatch\n{\n    internal static async Task Run(IServiceProvider services, RpcStream stream, RpcFrame open)\n    {\n        var context = stream.Context(open.Method);\n        switch (open.Method)\n        {\n");
foreach (var (service, methods) in services)
{
    client.Append($"    private sealed class {service[1..]}Client(IRpcClient client) : {service}\n    {{\n");
    foreach (var (kind, reply, method, request, arg) in methods)
    {
        var route = $"{service}/{method}";
        var inputType = request.StartsWith("IAsyncEnumerable<") ? request["IAsyncEnumerable<".Length..] : request;
        if (inputType.EndsWith('>')) inputType = inputType[..^1];
        var operation = request.StartsWith("IAsyncEnumerable<") ? "Duplex" : kind == "IAsyncEnumerable" ? "Stream" : "Unary";
        client.Append($"        public {kind}<{reply}> {method}({request} {arg}, CallContext context = default) => client.{operation}<{inputType}, {reply}>(\"{route}\", {arg}, context);\n");
        server.Append($"            case \"{route}\":\n            {{\n                var service = ActivatorUtilities.CreateInstance<{service[1..]}>(services);\n");
        string argument;
        if (operation == "Duplex") argument = $"stream.Read<{inputType}>()";
        else
        {
            server.Append($"                var request = await ReadOne<{request}>(stream);\n");
            argument = "request";
        }
        if (kind == "ValueTask") server.Append($"                await stream.Send(await service.{method}({argument}, context));\n");
        else server.Append($"                await foreach (var reply in service.{method}({argument}, context).WithCancellation(stream.Token)) await stream.Send(reply);\n");
        server.Append("                break;\n            }\n");
    }
    client.Append("    }\n");
}
client.Append("}\n");
server.Append("""
            default: throw new RpcException(new(StatusCode.Unimplemented, "Unknown host operation."));
        }
        await stream.Finish();
    }
    private static async Task<T> ReadOne<T>(RpcStream stream)
    {
        await using var input = stream.Read<T>().GetAsyncEnumerator();
        if (!await input.MoveNextAsync()) throw new RpcException(new(StatusCode.InvalidArgument, "Missing request."));
        var request = input.Current;
        if (await input.MoveNextAsync()) throw new RpcException(new(StatusCode.InvalidArgument, "Multiple unary requests."));
        return request;
    }
}

""");
File.WriteAllText("src/Tereditor.Host.Protocol/RpcServices.Generated.cs", client.ToString().TrimEnd(), utf8);
File.WriteAllText("src/Tereditor.Host.Remote/RpcDispatch.Generated.cs", server.ToString().TrimEnd(), utf8);

// The payload codec: one Write and one Read per [ProtoContract] class, byte-compatible with the
// protobuf-net 2.4 encoding the protocol started with (see the Host.Protocol SPEC's codec section). Each root is
// (project directory, namespace, codec file); the codec class is named after the file. The services above stay
// Protocol-only; the plugin isolation channel (Tereditor.Plugins.Isolation) has messages and no services.
(string Directory, string Namespace, string Output)[] codecRoots =
[
    ("src/Tereditor.Host.Protocol", "Tereditor.Host.Protocol", "RpcCodec.Generated.cs"),
    ("src/Tereditor.Plugins.Isolation", "Tereditor.Plugins.Isolation", "IsoCodec.Generated.cs"),
];
var memberPattern = new Regex(@"^\s*\[ProtoMember\((\d+)(, IsRequired = true)?\)(?:, System\.ComponentModel\.DefaultValue\(([^)]*)\))?\] public (\S+(?:, \S+)?) (\w+) \{ get; set; \}(?: = [^;]+;)?$");
var writes = new Dictionary<string, string> { ["int"] = "Int32", ["long"] = "Int64", ["bool"] = "Bool" };
foreach (var (directory, ns, output) in codecRoots) Generate(directory, ns, output);
return 0;

void Generate(string directory, string ns, string output)
{
    var sources = Sorted(directory, "*.cs").Where(path => !Path.GetFileName(path).EndsWith(".Generated.cs", StringComparison.Ordinal))
        .ToDictionary(path => path, Read);
    var enums = sources.Values.SelectMany(source => Regex.Matches(source, @"public enum (\w+)").Select(m => m.Groups[1].Value)).ToHashSet();
    var messages = new OrderedDictionary<string, List<(int Tag, bool Required, string? Default, string Kind, string Member)>>();
    foreach (var (path, source) in sources)
    {
        var name0 = Path.GetFileName(path);
        var found = Regex.Matches(source, @"\[ProtoContract\]\npublic sealed class (\w+)(;| \{ \}|\n\{\n(.*?)\n\})", RegexOptions.Singleline);
        if (found.Count != Count(source, "[ProtoContract]")) Fail($"{name0}: a [ProtoContract] is not directly followed by \"public sealed class Name\"");
        var parsed = 0;
        foreach (Match f in found)
        {
            var name = f.Groups[1].Value;
            var members = new List<(int, bool, string?, string, string)>();
            foreach (var line in f.Groups[3].Value.Split('\n'))
            {
                if (!line.Contains("[ProtoMember")) continue;
                var match = memberPattern.Match(line);
                if (!match.Success) Fail($"{name0}: unsupported member declaration: {line.Trim()}");
                var g = match.Groups;
                members.Add((int.Parse(g[1].Value), g[2].Success, g[3].Success ? g[3].Value : null, g[4].Value, g[5].Value));
            }
            if (members.Select(m => m.Item1).Distinct().Count() != members.Count) Fail($"{name}: duplicate field number");
            messages[name] = members.OrderBy(m => m.Item1).ToList();
            parsed += members.Count;
        }
        if (parsed != Count(source, "[ProtoMember")) Fail($"{name0}: parsed {parsed} members of {Count(source, "[ProtoMember")}");
    }

    (string Shape, string? Target) Classify(string kind)
    {
        var nullable = kind.EndsWith('?');
        var bare = nullable ? kind[..^1] : kind;
        if (bare is "string" or "byte[]") return (bare, null);
        if (bare is "int" or "long" or "bool") return ((nullable ? "nullable " : "") + bare, null);
        if (kind == "double") return ("double", null);
        if (enums.Contains(bare) && !nullable) return ("enum", bare);
        if (messages.ContainsKey(bare)) return ("message", bare);
        var item = Regex.Match(kind, @"^List<(\w+)>$");
        if (item.Success && item.Groups[1].Value == "string") return ("strings", null);
        if (item.Success && item.Groups[1].Value == "long") return ("longs", null);
        if (item.Success && messages.ContainsKey(item.Groups[1].Value)) return ("messages", item.Groups[1].Value);
        if (kind == "Dictionary<string, string>") return ("map", null);
        Fail($"unsupported wire type {kind}");
        return default;
    }

    var codecClass = output[..^".Generated.cs".Length];
    var codec = new StringBuilder(Header + $"#nullable enable\n\nusing Tereditor.Wire;\n\nnamespace {ns};\n\ninternal static class {codecClass}\n{{\n    internal static void Register()\n    {{\n");
    foreach (var name in messages.Keys)
    {
        codec.Append($"        RpcMessage<{name}>.Write = Write{name};\n");
        codec.Append($"        RpcMessage<{name}>.Read = static (ref ProtoReader reader) => Read{name}(ref reader, null);\n");
    }
    codec.Append("    }\n");
    foreach (var (name, members) in messages)
    {
        var write = new StringBuilder($"\n    private static void Write{name}(ProtoWriter writer, {name} value)\n    {{\n");
        var read = new StringBuilder($"\n    private static {name} Read{name}(ref ProtoReader reader, {name}? value)\n    {{\n        value ??= new();\n");
        if (members.Count == 0)
        {
            write.Append("    }\n");
            read.Append("        while (reader.Next()) reader.Skip();\n        return value;\n    }\n");
            codec.Append(write).Append(read);
            continue;
        }
        read.Append("        while (reader.Next())\n        {\n            switch (reader.Field)\n            {\n");
        foreach (var (tag, required, def, kind, member) in members)
        {
            var (shape, target) = Classify(kind);
            string field = $"value.{member}", local = $"field{tag}";
            if ((required || def is not null) && shape is not ("int" or "long" or "bool"))
                Fail($"{name}.{member}: IsRequired and DefaultValue are only supported on int, long and bool");
            if (shape is "int" or "long" or "bool")
            {
                var omitted = def ?? (shape == "bool" ? "false" : "0");
                var condition = required ? "" : omitted == "false" ? $"if ({field}) " : omitted == "true" ? $"if (!{field}) " : $"if ({field} != {omitted}) ";
                write.Append($"        {condition}writer.{writes[shape]}({tag}, {field});\n");
                read.Append($"                case {tag}: {field} = reader.{writes[shape]}(); break;\n");
            }
            else if (shape == "double")
            {
                write.Append($"        if ({field} != 0) writer.Double({tag}, {field});\n");
                read.Append($"                case {tag}: {field} = reader.Double(); break;\n");
            }
            else if (shape.StartsWith("nullable "))
            {
                var method = writes[shape["nullable ".Length..]];
                write.Append($"        if ({field} is {{ }} {local}) writer.{method}({tag}, {local});\n");
                read.Append($"                case {tag}: {field} = reader.{method}(); break;\n");
            }
            else if (shape == "enum")
            {
                write.Append($"        if ({field} != 0) writer.Int32({tag}, (int){field});\n");
                read.Append($"                case {tag}: {field} = ({target})reader.Int32(); break;\n");
            }
            else if (shape == "string")
            {
                write.Append($"        if ({field} is {{ }} {local}) writer.String({tag}, {local});\n");
                read.Append($"                case {tag}: {field} = reader.String(); break;\n");
            }
            else if (shape == "byte[]")
            {
                write.Append($"        if ({field} is {{ }} {local}) writer.Bytes({tag}, {local});\n");
                read.Append($"                case {tag}: {field} = reader.Bytes({field}); break;\n");
            }
            else if (shape == "message")
            {
                write.Append($"        if ({field} is {{ }} {local})\n        {{\n            var start = writer.BeginMessage({tag});\n            Write{target}(writer, {local});\n            writer.EndMessage(start);\n        }}\n");
                read.Append($"                case {tag}:\n                {{\n                    var outer = reader.Enter();\n                    {field} = Read{target}(ref reader, {field});\n                    reader.Leave(outer);\n                    break;\n                }}\n");
            }
            else if (shape == "strings")
            {
                write.Append($"        if ({field} is {{ }} {local})\n            foreach (var item in {local}) writer.String({tag}, item ?? throw new ArgumentNullException(nameof(value), \"A repeated RPC string is null.\"));\n");
                read.Append($"                case {tag}: ({field} ??= new()).Add(reader.String()); break;\n");
            }
            else if (shape == "longs")
            {
                write.Append($"        if ({field} is {{ }} {local})\n            foreach (var item in {local}) writer.Int64({tag}, item);\n");
                read.Append($"                case {tag}: ({field} ??= new()).Add(reader.Int64()); break;\n");
            }
            else if (shape == "messages")
            {
                write.Append($"        if ({field} is {{ }} {local})\n            foreach (var item in {local})\n            {{\n                var start = writer.BeginMessage({tag});\n                if (item is not null) Write{target}(writer, item);\n                writer.EndMessage(start);\n            }}\n");
                read.Append($"                case {tag}:\n                {{\n                    var outer = reader.Enter();\n                    ({field} ??= new()).Add(Read{target}(ref reader, null));\n                    reader.Leave(outer);\n                    break;\n                }}\n");
            }
            else
            {
                write.Append($"        if ({field} is {{ }} {local})\n            foreach (var (key, item) in {local})\n            {{\n                var start = writer.BeginMessage({tag});\n                if (key.Length > 0) writer.String(1, key);\n                if (!string.IsNullOrEmpty(item)) writer.String(2, item);\n                writer.EndMessage(start);\n            }}\n");
                read.Append($"                case {tag}:\n                {{\n                    var (key, item) = reader.StringEntry();\n                    ({field} ??= new())[key] = item;\n                    break;\n                }}\n");
            }
        }
        write.Append("    }\n");
        read.Append("                default: reader.Skip(); break;\n            }\n        }\n        return value;\n    }\n");
        codec.Append(write).Append(read);
    }
    codec.Append("}\n");
    File.WriteAllText(Path.Combine(directory, output), codec.ToString().TrimEnd(), utf8);
}

static int Count(string text, string needle)
{
    int count = 0, at = 0;
    while ((at = text.IndexOf(needle, at, StringComparison.Ordinal)) >= 0) { count++; at += needle.Length; }
    return count;
}
