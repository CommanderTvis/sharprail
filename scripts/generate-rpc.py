"""Generate typed WebSocket clients and direct dispatch from the host contracts.
Run with: uv run --no-project python scripts/generate-rpc.py
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
services = {}
for path in sorted((root / 'src/SharpRail.Host.Protocol').glob('*Contract.cs')):
    source = path.read_text()
    match = re.search(r'public (?:partial )?interface (I\w+Rpc)', source)
    if not match:
        continue
    methods = re.findall(r'(ValueTask|IAsyncEnumerable)<(\w+)> (\w+)\((IAsyncEnumerable<\w+>|\w+) (\w+), CallContext context = default\);', source)
    services.setdefault(match[1], []).extend(methods)
header = '// Generated by scripts/generate-rpc.py from the host contracts.\n'
client = header + 'namespace SharpRail.Host.Protocol;\n\npublic static class RpcServices\n{\n    public static T Create<T>(IRpcClient client) => (T)(object)(typeof(T).Name switch\n    {\n'
for service in services:
    client += f'        nameof({service}) => new {service[1:]}Client(client),\n'
client += '        _ => throw new NotSupportedException(typeof(T).FullName)\n    });\n'
server = header + 'using SharpRail.Host.Protocol;\n\nnamespace SharpRail.Host.Remote;\n\ninternal static class RpcDispatch\n{\n    internal static async Task Run(IServiceProvider services, RpcStream stream, RpcFrame open)\n    {\n        var context = stream.Context(open.Method);\n        switch (open.Method)\n        {\n'
for service, methods in services.items():
    client += f'    private sealed class {service[1:]}Client(IRpcClient client) : {service}\n    {{\n'
    for kind, reply, method, request, arg in methods:
        route = f'{service}/{method}'
        input_type = request.removeprefix('IAsyncEnumerable<').removesuffix('>')
        operation = 'Duplex' if request.startswith('IAsyncEnumerable<') else 'Stream' if kind == 'IAsyncEnumerable' else 'Unary'
        client += f'        public {kind}<{reply}> {method}({request} {arg}, CallContext context = default) => client.{operation}<{input_type}, {reply}>("{route}", {arg}, context);\n'
        server += f'            case "{route}":\n            {{\n                var service = ActivatorUtilities.CreateInstance<{service[1:]}>(services);\n'
        if operation == 'Duplex':
            argument = f'stream.Read<{input_type}>()'
        else:
            server += f'                var request = await ReadOne<{request}>(stream);\n'
            argument = 'request'
        if kind == 'ValueTask':
            server += f'                await stream.Send(await service.{method}({argument}, context));\n'
        else:
            server += f'                await foreach (var reply in service.{method}({argument}, context).WithCancellation(stream.Token)) await stream.Send(reply);\n'
        server += '                break;\n            }\n'
    client += '    }\n'
client += '}\n'
server += '''            default: throw new RpcException(new(StatusCode.Unimplemented, "Unknown host operation."));
        }
        await stream.Finish();
    }
    private static async Task<T> ReadOne<T>(RpcStream stream)
    {
        await using var input = stream.Read<T>().GetAsyncEnumerator();
        if (!await input.MoveNextAsync()) throw new RpcException(new(StatusCode.InvalidArgument, "Missing request."));
        var request = input.Current;
        if (await input.MoveNextAsync()) throw new RpcException(new(StatusCode.InvalidArgument, "Multiple unary requests."));
        return request;
    }
}
'''
(root / 'src/SharpRail.Host.Protocol/RpcServices.Generated.cs').write_text(client.rstrip())
(root / 'src/SharpRail.Host.Remote/RpcDispatch.Generated.cs').write_text(server.rstrip())
