"""Builds the Zig dependency mirror archive and scripts/zig-deps.lock from measured Zig global caches.

Usage: uv run --no-project python scripts/zig-deps-pack.py <out-dir> <view-cache> <vt-cache> <zon-root>...
<view-cache> is the global cache of the Zig 0.14 view build (package directories under p/), <vt-cache> that of the Zig 0.16
build (p/<hash>.tar.gz files), <zon-root> a directory searched for build.zig.zon files to learn each package's URL.
Every package hosted outside github.com and deps.files.ghostty.org (the hosts that are fetched upstream by design) goes into the archive. Run by scripts/mise run zig-deps:mirror.
"""
import gzip, hashlib, io, os, re, sys, tarfile
from urllib.parse import urlparse

out, view, vt, *roots = sys.argv[1:]
urls = {}
for root in roots:
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in ('.git', 'node_modules')]
        if 'build.zig.zon' in files:
            text = open(os.path.join(base, 'build.zig.zon'), encoding='utf-8').read()
            for m in re.finditer(r'\.url\s*=\s*"([^"]+)",\s*\.hash\s*=\s*"([^"]+)"', text):
                urls[m.group(2)] = m.group(1)

def host(url):
    return urlparse(url[4:] if url.startswith('git+') else url).hostname

forms = {}
for entry in sorted(os.listdir(os.path.join(view, 'p'))):
    if os.path.isdir(os.path.join(view, 'p', entry)): forms.setdefault(entry, set()).add('dir')
for entry in sorted(os.listdir(os.path.join(vt, 'p'))):
    if entry.endswith('.tar.gz'): forms.setdefault(entry[:-7], set()).add('tgz')

picked = {}
for pkg, f in forms.items():
    url = urls.get(pkg)
    if url is None:
        if 'tgz' in f and len(f) == 1 and pkg.startswith('aro-'): url = 'https://github.com/vancluever/arocc'  # named by translate_c
        else: sys.exit(f'No URL known for package {pkg}; pass the source roots that declare it.')
    if host(url) not in ('github.com', 'deps.files.ghostty.org'): picked[pkg] = ('+'.join(sorted(f)), url)

lines = [f'{p} {form}' for p, (form, _) in sorted(picked.items())]
ident = hashlib.sha256('\n'.join(lines).encode()).hexdigest()[:12]
name = f'zig-deps-{ident}.tar.gz'
os.makedirs(out, exist_ok=True)
raw = io.BytesIO()
with tarfile.open(fileobj=raw, mode='w', format=tarfile.PAX_FORMAT) as tar:
    def add(path, arc):
        def norm(i): i.uid = i.gid = 0; i.uname = i.gname = ''; i.mtime = 0; return i
        tar.add(path, arc, filter=norm)
    for pkg, (form, _) in sorted(picked.items()):
        if 'dir' in form: add(os.path.join(view, 'p', pkg), 'p/' + pkg)
        if 'tgz' in form: add(os.path.join(vt, 'p', pkg + '.tar.gz'), f'p/{pkg}.tar.gz')
path = os.path.join(out, name)
with open(path, 'wb') as f, gzip.GzipFile(fileobj=f, mode='wb', mtime=0, filename='') as gz: gz.write(raw.getvalue())
digest = hashlib.sha256(open(path, 'rb').read()).hexdigest()
lock = [
    '# Mirror of the Zig packages the native builds fetch from hosts other than github.com and deps.files.ghostty.org (see scripts/zig-deps.sh).',
    '# Packages on GitHub and on Ghostty\'s own CDN (deps.files.ghostty.org) are fetched upstream by design and not listed here.',
    '# Generated by scripts/mise run zig-deps:mirror; do not edit. pkg <package-hash> <dir|tgz|dir+tgz> <upstream-url>:',
    '# dir = extracted directory in the global cache p/ (Zig 0.14), tgz = p/<hash>.tar.gz (Zig 0.16).',
    'repo CommanderTvis/sharprail', f'tag zig-deps-{ident}', f'asset {name}', f'sha256 {digest}',
    f'pin GHOSTTY_VIEW_COMMIT {os.environ["GHOSTTY_VIEW_COMMIT"]}', f'pin GHOSTTY_VT_COMMIT {os.environ["GHOSTTY_VT_COMMIT"]}']
lock += [f'pkg {p} {form} {url}' for p, (form, url) in sorted(picked.items())]
open(os.path.join(out, 'zig-deps.lock'), 'w').write('\n'.join(lock) + '\n')
print(path, digest, len(picked), 'packages')
